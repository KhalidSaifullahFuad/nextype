//! Clipboard context (spec §7.3): text the user copied recently, if the setting is on.
//! Main thread only (NSPasteboard and the poll timer live there).

use std::cell::Cell;
use std::sync::atomic::{AtomicIsize, Ordering};
use std::time::{Duration, Instant};

use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;

/// Older copies are left out (`pasteboardMaxAgeSeconds`; spec suggests 120 s).
const MAX_AGE: Duration = Duration::from_secs(120);
/// Long copies are cut before tokenizing; the prompt budget cuts further.
const MAX_CHARS: usize = 2000;
/// nspasteboard.org markers: passwords, our own paste, and generated content are never used.
const PRIVATE_TYPES: [&str; 3] =
    ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

/// Change count of the clipboard our paste fallback put back; it is the user's old copy, not a new one.
pub static RESTORED: AtomicIsize = AtomicIsize::new(-1);

thread_local! {
    /// Last change count seen and when the user copied it (None: before launch, age unknown).
    static SEEN: Cell<(isize, Option<Instant>)> = Cell::new((NSPasteboard::generalPasteboard().changeCount(), None));
}

/// Called from the app poll timer so copy times are known to within a poll interval.
pub fn poll() {
    let count = NSPasteboard::generalPasteboard().changeCount();
    SEEN.with(|s| {
        let (seen, at) = s.get();
        if count != seen {
            let ours = count == RESTORED.load(Ordering::Relaxed) || has_private_type();
            s.set((count, if ours { at } else { Some(Instant::now()) }));
        }
    });
}

/// The copied text, if it is recent and not marked private.
pub fn recent_text() -> Option<String> {
    poll();
    SEEN.with(|s| s.get().1).filter(|at| at.elapsed() <= MAX_AGE)?;
    if has_private_type() {
        return None;
    }
    let text = NSPasteboard::generalPasteboard().stringForType(unsafe { NSPasteboardTypeString })?.to_string();
    let text: String = text.trim().chars().take(MAX_CHARS).collect();
    (!text.is_empty()).then_some(text)
}

fn has_private_type() -> bool {
    let Some(types) = NSPasteboard::generalPasteboard().types() else { return false };
    PRIVATE_TYPES.iter().any(|t| types.containsObject(&NSString::from_str(t)))
}
